const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { spawn } = require('node:child_process');

test('API cobre autenticação, artigos, segurança e diagnóstico', async t => {
  const dataDir = fs.mkdtempSync(path.join(os.tmpdir(), 'biblio-api-test-'));
  const port = 20000 + process.pid % 20000;
  const origin = `http://127.0.0.1:${port}`;
  const child = spawn(process.execPath, ['server.js'], { cwd: path.join(__dirname, '..'), env: { ...process.env, DATA_DIR: dataDir, PORT: String(port) }, stdio: ['ignore', 'pipe', 'pipe'] });
  let errors = '';
  child.stderr.on('data', chunk => { errors += chunk; });
  t.after(async () => {
    if (child.exitCode === null) {
      child.kill();
      await new Promise(resolve => child.once('exit', resolve));
    }
    fs.rmSync(dataDir, { recursive: true, force: true });
  });
  for (let attempt = 0; attempt < 240; attempt++) {
    try { if ((await fetch(origin + '/api/health')).ok) break; } catch {}
    await new Promise(resolve => setTimeout(resolve, 50));
    if (attempt === 239) throw new Error('Servidor de teste não iniciou: ' + errors);
  }

  const health = await fetch(origin + '/api/health');
  assert.equal(health.headers.get('x-frame-options'), 'DENY');
  assert.match(health.headers.get('content-security-policy'), /frame-ancestors 'none'/);

  const setup = await fetch(origin + '/api/auth/setup', { method: 'POST', headers: { 'content-type': 'application/json', origin }, body: JSON.stringify({ username: 'teste', password: 'senha-segura-123' }) });
  assert.equal(setup.status, 201);
  const cookie = setup.headers.get('set-cookie').split(';')[0];
  const headers = { 'content-type': 'application/json', cookie, origin };
  assert.equal((await fetch(origin + '/api/calendar/holidays')).status, 401);
  assert.deepEqual(await fetch(origin + '/api/calendar/holidays', { headers }).then(r => r.json()), []);
  const holidayResponse = await fetch(origin + '/api/calendar/holidays', { method: 'POST', headers, body: JSON.stringify({ name: 'Aniversário da cidade', date: '2026-10-15', annual: true }) });
  assert.equal(holidayResponse.status, 201);
  const holiday = await holidayResponse.json();
  const savedHolidays = await fetch(origin + '/api/calendar/holidays', { headers }).then(r => r.json());
  assert.equal(savedHolidays[0].id, holiday.id);
  assert.equal(savedHolidays[0].annual, 1);
  assert.equal(savedHolidays[0].name, 'Aniversário da cidade');
  for (const payload of [{ name: 'Inválido', date: '2026-02-30', annual: true }, { name: ' ', date: '2026-10-15', annual: true }, { name: 'Inválido', date: '2026-10-15', annual: 'false' }]) {
    assert.equal((await fetch(origin + '/api/calendar/holidays', { method: 'POST', headers, body: JSON.stringify(payload) })).status, 400);
  }
  assert.equal((await fetch(origin + '/api/calendar/holidays/' + holiday.id, { method: 'DELETE', headers })).status, 204);
  assert.equal((await fetch(origin + '/api/calendar/holidays/' + holiday.id, { method: 'DELETE', headers })).status, 404);
  const appearancePng = Buffer.concat([Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]), Buffer.alloc(24)]);
  const appearanceUpload = await fetch(origin + '/api/settings/images/banner', { method: 'POST', headers: { ...headers, 'content-type': 'application/octet-stream', 'x-mime-type': 'image/png' }, body: appearancePng });
  assert.equal(appearanceUpload.status, 200);
  assert.match((await fetch(origin + '/api/settings', { headers }).then(response => response.json())).banner_image, /^data:image\/png;base64,/);
  const bible = await fetch(origin + '/api/bible', { headers }).then(response => response.json());
  assert.equal(bible.books.length, 66);
  assert.equal(bible.books.filter(book => book.testament === 'old').length, 39);
  assert.equal(bible.books.filter(book => book.testament === 'new').length, 27);
  const john316 = await fetch(origin + '/api/bible/books/JHN/chapters/3', { headers }).then(response => response.json());
  assert.match(john316.verses.find(verse => verse.verse === '16').text, /Deus amou/);
  assert.deepEqual(john316.highlights, []);
  const highlightResponse = await fetch(origin + '/api/bible/highlights', { method: 'PUT', headers, body: JSON.stringify({ book_code: 'JHN', chapter: 3, verse: '16', color: 'yellow', note: 'O amor de Deus.' }) });
  assert.equal(highlightResponse.status, 200);
  const highlight = await highlightResponse.json();
  assert.equal(highlight.book_name, 'João');
  assert.equal(highlight.color, 'yellow');
  assert.match(highlight.verse_text, /Deus amou/);
  const highlightedChapter = await fetch(origin + '/api/bible/books/JHN/chapters/3', { headers }).then(response => response.json());
  assert.equal(highlightedChapter.highlights[0].note, 'O amor de Deus.');
  const highlightIndex = await fetch(origin + '/api/bible/highlights?q=amor&color=yellow', { headers }).then(response => response.json());
  assert.equal(highlightIndex.results.length, 1);
  const changedHighlight = await fetch(origin + '/api/bible/highlights', { method: 'PUT', headers, body: JSON.stringify({ book_code: 'JHN', chapter: 3, verse: '16', color: 'blue', note: 'Nota atualizada.' }) }).then(response => response.json());
  assert.equal(changedHighlight.id, highlight.id);
  assert.equal(changedHighlight.color, 'blue');
  const invalidHighlight = await fetch(origin + '/api/bible/highlights', { method: 'PUT', headers, body: JSON.stringify({ book_code: 'JHN', chapter: 3, verse: '999', color: 'yellow' }) });
  assert.equal(invalidHighlight.status, 404);
  assert.equal((await fetch(origin + '/api/bible/highlights/' + highlight.id, { method: 'DELETE', headers })).status, 204);
  assert.equal((await fetch(origin + '/api/bible/highlights', { headers }).then(response => response.json())).results.length, 0);
  const bibleSearch = await fetch(origin + '/api/bible/search?q=' + encodeURIComponent('Deus amou'), { headers }).then(response => response.json());
  assert.ok(bibleSearch.results.length > 0);
  assert.equal((await fetch(origin + '/api/dictionary')).status, 401);
  const dictionary = await fetch(origin + '/api/dictionary', { headers }).then(r => r.json());
  assert.equal(dictionary.source.language, 'pt');
  assert.equal(dictionary.source.incomplete, true);
  assert.equal(dictionary.entries.length, 61);
  assert.match(dictionary.source.license, /CC BY-SA 4.0/);
  const dictionarySearch = await fetch(origin + '/api/dictionary/search?q=abraao', { headers }).then(r => r.json());
  const abraham = dictionarySearch.results.find(entry => entry.title === 'Abraão');
  assert.ok(abraham);
  const dictionaryEntry = await fetch(origin + '/api/dictionary/entries/' + abraham.id, { headers }).then(r => r.json());
  assert.match(dictionaryEntry.text, /Pai de uma multidão/);
  assert.match(dictionaryEntry.source_url, /oldid=/);
  assert.match(dictionaryEntry.history_url, /action=history/);
  assert.equal((await fetch(origin + '/api/dictionary/entries/999999', { headers })).status, 404);
  assert.equal((await fetch(origin + '/api/dictionary/search?q=***', { headers })).status, 400);
  assert.deepEqual((await fetch(origin + '/api/dictionary/search?q=zzzzzzzzzzzz', { headers }).then(r => r.json())).results, []);
  const englishDictionary = await fetch(origin + '/api/dictionary?lang=en', { headers }).then(r => r.json());
  assert.equal(englishDictionary.source.language, 'en');
  assert.equal(englishDictionary.entries.length, 3963);
  assert.match(englishDictionary.source.license, /Public Domain/);
  const englishSearch = await fetch(origin + '/api/dictionary/search?lang=en&q=faith', { headers }).then(r => r.json());
  const faith = englishSearch.results.find(entry => entry.title.toLowerCase() === 'faith');
  assert.ok(faith);
  const faithEntry = await fetch(origin + '/api/dictionary/entries/' + faith.id + '?lang=en', { headers }).then(r => r.json());
  assert.match(faithEntry.source_url, /dictionaries.getbible.net/);
  assert.ok(faithEntry.text.length > 100);
  assert.equal((await fetch(origin + '/api/dictionary?lang=fr', { headers })).status, 400);
  const portugueseOnly = await fetch(origin + '/api/dictionary/search?lang=pt&q=faith', { headers }).then(r => r.json());
  assert.deepEqual(portugueseOnly.results, []);
  assert.equal((await fetch(origin + '/api/dictionary?lang=pt', { headers }).then(r => r.json())).entries.length, 61);
  const hebrewInfo = await fetch(origin + '/api/hebrew', { headers }).then(response => response.json());
  assert.equal(hebrewInfo.counts.entries, 7597);
  assert.match(hebrewInfo.source.license, /CC BY-SA 4\.0/);
  const hebrewSearch = await fetch(origin + '/api/hebrew/search?q=shalom', { headers }).then(response => response.json());
  assert.ok(hebrewSearch.results.length > 0);
  assert.equal(hebrewSearch.results[0].lemma_plain, 'שלום');
  const hebrewEntry = await fetch(origin + '/api/hebrew/entries/' + hebrewSearch.results[0].id, { headers }).then(response => response.json());
  assert.ok(hebrewEntry.senses.some(sense => sense.glosses.some(gloss => /paz/i.test(gloss))));
  assert.ok(hebrewEntry.senses.some(sense => sense.references.length));
  const home = await fetch(origin + '/api/home', { headers }).then(response => response.json());
  assert.equal(home.is_library_home, 1);
  assert.match(home.content, /Bem-vindo/);
  const updatedHome = await fetch(origin + '/api/articles/' + home.id, { method: 'PUT', headers, body: JSON.stringify({ title: 'Início personalizado', content: '<h2>Minha biblioteca</h2><p>Conteúdo próprio.</p>' }) }).then(response => response.json());
  assert.equal(updatedHome.title, 'Início personalizado');
  assert.equal(updatedHome.theme, null);
  assert.equal((await fetch(origin + '/api/articles/' + home.id, { method: 'DELETE', headers })).status, 400);
  const themes = await fetch(origin + '/api/themes', { headers }).then(response => response.json());
  const article = await fetch(origin + '/api/articles', { method: 'POST', headers, body: JSON.stringify({ title: 'Artigo', theme_id: themes[0].id, title_size: 2.5, title_margin_top: 12, title_margin_bottom: 24, content: '<script>não</script><p style="text-align:justify">Sim</p>', authors: 'Autora', tags: 'Teste' }) }).then(response => response.json());
  assert.equal(article.title, 'Artigo');
  assert.equal(article.title_size, 2.5);
  assert.equal(article.title_margin_top, 12);
  assert.equal(article.title_margin_bottom, 24);
  assert.doesNotMatch(article.content, /script/);
  assert.match(article.content, /text-align:justify/);

  const fakeUpload = await fetch(`${origin}/api/articles/${article.id}/attachments`, { method: 'POST', headers, body: JSON.stringify({ name: 'falsa.png', dataUrl: 'data:image/png;base64,ZmFsc2E=' }) });
  assert.equal(fakeUpload.status, 400);
  const png = Buffer.concat([Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]), Buffer.alloc(24)]);
  const uploaded = await fetch(`${origin}/api/articles/${article.id}/attachments`, { method: 'POST', headers: { ...headers, 'content-type': 'application/octet-stream', 'x-file-name': encodeURIComponent('imagem.png'), 'x-mime-type': 'image/png' }, body: png });
  assert.equal(uploaded.status, 201);
  const attachment = await uploaded.json();
  assert.equal(attachment.size_bytes, png.length);
  const diagnostics = await fetch(origin + '/api/diagnostics', { headers }).then(response => response.json());
  assert.equal(diagnostics.ok, true);
  assert.deepEqual(diagnostics.database, ['ok']);
  assert.deepEqual(diagnostics.media, { missing: [], orphaned: [] });
  assert.deepEqual(diagnostics.bible, { books: 66, verses: 31102 });
  assert.deepEqual(diagnostics.hebrew, { entries: 7597, senses: 15272 });
  const backup = await fetch(origin + '/api/backup', { headers });
  assert.equal(backup.status, 200);
  assert.equal(backup.headers.get('content-type'), 'application/zip');
  assert.ok((await backup.arrayBuffer()).byteLength > 0);

  const foreign = await fetch(origin + '/api/themes', { method: 'POST', headers: { ...headers, origin: 'http://example.com' }, body: JSON.stringify({ name: 'Bloqueado' }) });
  assert.equal(foreign.status, 403);
});
